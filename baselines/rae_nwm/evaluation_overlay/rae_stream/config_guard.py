def _number(value: Any, name: str) -> float:
    if isinstance(value, bool):
        raise ValueError(f"{name} must be numeric")
    try:
        result = float(value)
    except (TypeError, ValueError) as exc:
        raise ValueError(f"{name} must be numeric") from exc
    if not math.isfinite(result):
        raise ValueError(f"{name} must be finite")
    return result


def _equal(a: Any, b: Any) -> bool:
    """Deep equality that handles NumPy/Torch scalar-like values safely."""

    if isinstance(a, Mapping) and isinstance(b, Mapping):
        return set(a) == set(b) and all(_equal(a[key], b[key]) for key in a)
    if isinstance(a, (list, tuple)) and isinstance(b, (list, tuple)):
        return len(a) == len(b) and all(_equal(x, y) for x, y in zip(a, b))
    try:
        result = a == b
        if hasattr(result, "all"):
            return bool(result.all())
        return bool(result)
    except Exception:
        return a is b


def changed_keys(
    base: Mapping[str, Any],
    overlay: Mapping[str, Any],
    *,
    allowed_keys: Iterable[str] | None = None,
) -> list[str]:
    """Return changed top-level keys and reject non-data overlay changes.

    The function deliberately reports top-level names (rather than a noisy
    recursive path set) because a dataset replacement is one scientific
    identity change even when several nested paths differ.
    """

    if not isinstance(base, Mapping) or not isinstance(overlay, Mapping):
        raise TypeError("base and overlay must be mappings")
    # Keep a sentinel for absent keys.  ``dict.get`` alone would incorrectly
    # treat an omitted key and an explicit ``null`` as equal, which could let
    # an overlay silently remove a training option.
    changed_original: list[Any] = []
    for key in set(base) | set(overlay):
        left = base[key] if key in base else _MISSING
        right = overlay[key] if key in overlay else _MISSING
        if not _equal(left, right):
            changed_original.append(key)
    keys = sorted({str(key) for key in changed_original})
    admitted = ALLOWED_OVERLAY_KEYS if allowed_keys is None else frozenset(str(key) for key in allowed_keys)
    forbidden = [key for key in keys if key not in admitted]
    if forbidden:
        raise ValueError(
            "overlay changes not allowed under paper-reproduction profile: "
            + ", ".join(forbidden)
        )
    return keys


def runtime_paper_config(
    config: Mapping[str, Any],
    *,
    world_size: int = 1,
    gradient_accumulation_steps: int | None = None,
) -> dict[str, Any]:
    """Derive the per-rank YAML consumed by the official trainer.

    The checked-in template remains the paper's total-batch (96) world-one
    config.  A formal runtime may explicitly request accumulation; in that
    case this pure shallow-copying helper adds only the two derived runtime
    fields and sets the per-rank microbatch so
    ``world * microbatch * accumulation == 96`` exactly.
    """

    if not isinstance(config, Mapping):
        raise TypeError("config must be a mapping")
    if gradient_accumulation_steps is None:
        # Preserve the old world-only API when no runtime field is requested.
        steps = require_positive_int(
            config.get("gradient_accumulation_steps", 1),
            name="gradient_accumulation_steps",
        )
    else:
        steps = gradient_accumulation_steps
    plan = make_accumulation_plan(
        global_batch_size=int(PAPER_TRAINING_PROFILE["global_batch_size"]),
        world_size=world_size,
        accumulation_steps=steps,
    )
    result = dict(config)
    result["batch_size"] = plan.microbatch_size
    if plan.accumulation_steps != 1:
        result["gradient_accumulation_steps"] = plan.accumulation_steps
        result["effective_global_batch_size"] = plan.effective_global_batch_size
        result["training_profile"] = training_profile_name(plan.accumulation_steps)
        result["paper_training_profile"] = PAPER_PROFILE_NAME
    return result


def assert_runtime_paper_config(
    template: Mapping[str, Any],
    resolved: Mapping[str, Any],
    *,
    world_size: int = 1,
    gradient_accumulation_steps: int | None = None,
    epochs: int = 50,
) -> None:
    """Validate a generated per-rank config against the checked-in template.

    Only the derived ``batch_size`` and explicit runtime accumulation fields
    may differ.  This closes the common failure mode where a hand-written
    temporary YAML silently changes a model or optimizer field.
    """

    if not isinstance(template, Mapping) or not isinstance(resolved, Mapping):
        raise TypeError("template and resolved configs must be mappings")
    if gradient_accumulation_steps is None:
        gradient_accumulation_steps = resolved.get("gradient_accumulation_steps", None)
    expected = runtime_paper_config(
        template,
        world_size=world_size,
        gradient_accumulation_steps=gradient_accumulation_steps,
    )
    if set(resolved) != set(expected):
        raise ValueError("runtime config keys differ from the reviewed paper template")
    changed = [key for key in expected if not _equal(expected[key], resolved[key])]
    if changed:
        raise ValueError(
            "runtime config may change only derived batch/accumulation fields; "
            "mismatch in " + ", ".join(sorted(str(key) for key in changed))
        )
    assert_training_profile(
        resolved,
        epochs=epochs,
        world_size=world_size,
        gradient_accumulation_steps=gradient_accumulation_steps,
    )


def assert_training_profile(
    config: Mapping[str, Any],
    *,
    epochs: int = 50,
    world_size: int = 1,
    gradient_accumulation_steps: int | None = None,
) -> None:
    """Require the exact paper-stated RAE-NWM training profile.

    ``world_size`` and accumulation are runtime topology/memory settings, not
    model hyperparameters.  Their product determines the per-rank microbatch;
    the effective global batch remains fixed at 96.
    """

    if not isinstance(config, Mapping):
        raise TypeError("resolved config must be a mapping")
    mismatches: list[str] = []
    if gradient_accumulation_steps is None:
        gradient_accumulation_steps = config.get("gradient_accumulation_steps", 1)
    try:
        expected_batch = paper_batch_mapping(
            {
                "batch_size": config.get("batch_size", _MISSING),
                "gradient_accumulation_steps": gradient_accumulation_steps,
                **(
                    {"effective_global_batch_size": config["effective_global_batch_size"]}
                    if "effective_global_batch_size" in config
                    else {}
                ),
            },
            world_size=world_size,
            gradient_accumulation_steps=gradient_accumulation_steps,
        )["per_rank_batch_size"]
    except (TypeError, ValueError) as exc:
        mismatches.append(f"batch_size=<invalid> ({exc})")
        expected_batch = None
    for key in ("batch_size", "lr", "final_lr", "lr_schedule", "weight_decay", "num_workers"):
        expected = expected_batch if key == "batch_size" and expected_batch is not None else OFFICIAL_CHECKOUT_PROFILE[key]
        if key not in config:
            mismatches.append(f"{key}=<missing> (expected {expected})")
            continue
        actual = config[key]
        if key in {"lr", "final_lr", "weight_decay"}:
            try:
                same = math.isclose(float(actual), float(expected), rel_tol=0.0, abs_tol=1e-15)
            except (TypeError, ValueError):
                same = False
        elif key == "lr_schedule":
            same = str(actual).strip().lower() == str(expected).lower()
        else:
            try:
                same = require_positive_int(actual, name=key) == require_positive_int(
                    expected, name=key
                )
            except ValueError:
                same = False
        if not same:
            mismatches.append(f"{key}={actual!r} (expected {expected!r})")
    try:
        epochs_value = require_positive_int(epochs, name="epochs")
    except ValueError:
        epochs_value = None
    if epochs_value != int(OFFICIAL_CHECKOUT_PROFILE["epochs"]):
        mismatches.append(f"epochs={epochs!r} (expected {OFFICIAL_CHECKOUT_PROFILE['epochs']!r})")
    if mismatches:
        raise ValueError(
            "paper-reproduction (official-checkout-config compatibility guard) profile mismatch; refusing implicit training override: "
            + "; ".join(mismatches)
        )
    mapping = paper_batch_mapping(
        config,
        world_size=world_size,
        gradient_accumulation_steps=gradient_accumulation_steps,
    )
    if "effective_global_batch_size" in config and mapping.get("effective_global_batch_size") != 96:
        raise ValueError("effective global batch must remain 96")


def assert_no_resume_settings(config: Mapping[str, Any]) -> None:
    """Reject every config route that can load a prior training state."""

    forbidden = ("from_checkpoint", "checkpoint_path", "override_lr_on_resume")
    present = [key for key in forbidden if key in config]
    if present:
        raise ValueError(
            "RAE-stream paper-reproduction-v1 is a fresh run; resume settings are forbidden: "
            + ", ".join(present)
        )


def assert_fresh_training_output(repo_root: str | Path, config: Mapping[str, Any]) -> Path:
    """Resolve the official output path and refuse implicit ``latest`` resume.

    Upstream ``train.py`` automatically restores
    ``results_dir/run_name/checkpoints/latest.pth.tar``.  The B1 identity is a
    fresh official-checkout run, so the gate must run immediately before
    spawn and fail rather than silently changing initialization/epoch state.
    """

    assert_no_resume_settings(config)
    root = Path(repo_root).resolve()
    results_value = config.get("results_dir")
    run_value = config.get("run_name")
    if not isinstance(results_value, str) or not results_value:
        raise ValueError("results_dir must be a non-empty relative output path")
    if not isinstance(run_value, str) or not run_value or Path(run_value).name != run_value:
        raise ValueError("run_name must be one safe output path component")
    results = Path(results_value)
    if results.is_absolute() or ".." in results.parts:
        raise ValueError("results_dir must be a relative output path")
    experiment_lexical = root / results / run_value
    try:
        experiment_lexical.relative_to(root)
    except ValueError as exc:
        raise ValueError("training output must remain below the RAE-stream repo root") from exc
    # Existing symlink components can redirect logs/checkpoints outside the
    # reviewed worktree even when ``resolve()`` is later used for bookkeeping.
    current = root
    for component in (*results.parts, run_value):
        current = current / component
        if current.is_symlink():
            raise ValueError(f"training output contains a symlink component: {current}")
    experiment = experiment_lexical.resolve()
    try:
        experiment.relative_to(root)
    except ValueError as exc:
        raise ValueError("training output resolves outside the RAE-stream repo root") from exc
    if experiment.exists():
        if experiment.is_symlink() or not experiment.is_dir():
            raise ValueError(f"training output is not a regular directory: {experiment}")
        try:
            existing = list(experiment.iterdir())
        except OSError as exc:
            raise RuntimeError(f"could not inspect existing training output: {experiment}") from exc
        if existing:
            raise RuntimeError(
                f"training output is not fresh (implicit resume/contamination target): {experiment}"
            )
    latest = experiment / "checkpoints" / "latest.pth.tar"
    if latest.exists():
        raise RuntimeError(
            f"implicit upstream resume target already exists: {latest}; "
            "use a separately reviewed resume profile instead of RAE-stream B1"
        )
    return experiment


def assert_data_overlay(base: Mapping[str, Any], overlay: Mapping[str, Any]) -> list[str]:
    """Validate an overlay and return its changed identity keys."""

    assert_no_resume_settings(overlay)
    changed = changed_keys(
        base,
        overlay,
        allowed_keys=ALLOWED_OVERLAY_KEYS | PAPER_PROFILE_OVERLAY_KEYS,
    )
    # The base checkout predates the paper's published training recipe.  An
    # overlay may therefore change only the exact paper values above; arbitrary
    # memory-reduction or tuning changes remain forbidden.
    for key in sorted(set(changed) & PAPER_PROFILE_OVERLAY_KEYS):
        expected = OFFICIAL_CHECKOUT_PROFILE[key]
        actual = overlay.get(key, _MISSING)
        if key in {"lr", "final_lr", "weight_decay"}:
            try:
                matches = math.isclose(float(actual), float(expected), rel_tol=0.0, abs_tol=1e-15)
            except (TypeError, ValueError):
                matches = False
        elif key == "lr_schedule":
            matches = str(actual).strip().lower() == str(expected).lower()
        else:
            try:
                matches = int(actual) == int(expected) and not isinstance(actual, bool)
            except (TypeError, ValueError):
                matches = False
        if not matches:
            raise ValueError(
                f"paper-reproduction overlay value for {key} must be {expected!r}; got {actual!r}"
            )
    # A changed dataset map must contain the dedicated dataset name and must
    # not accidentally retain another training source in the run config.
    if "datasets" in changed:
        datasets = overlay.get("datasets")
        if not isinstance(datasets, Mapping) or "rae_stream" not in datasets:
            raise ValueError("data overlay must define datasets.rae_stream")
        # B1 is a same-data comparison, not a mixed-source training run.  A
        # stray recon/sacson/scand entry would make the official loader read
        # another corpus even though the run is labelled RAE-stream.
        if set(datasets) != {"rae_stream"}:
            raise ValueError(
                "data overlay must contain only datasets.rae_stream; mixed training sources are forbidden"
            )
        entry = datasets.get("rae_stream")
        if not isinstance(entry, Mapping) or set(entry) != set(RAE_STREAM_DATASET_KEYS):
            raise ValueError(
                "datasets.rae_stream must contain exactly the reviewed loader keys: "
                + ", ".join(sorted(RAE_STREAM_DATASET_KEYS))
            )
        if entry.get("goals_per_obs") != 4 or isinstance(entry.get("goals_per_obs"), bool):
            raise ValueError("datasets.rae_stream goals_per_obs is fixed at 4")
        for key in ("data_folder", "train", "test"):
            value = entry.get(key)
            if not isinstance(value, str) or not value or Path(value).is_absolute() or ".." in Path(value).parts:
                raise ValueError(f"datasets.rae_stream {key} must be a relative traversal-free path")
    return changed


def is_allowed_untracked_path(path: str) -> bool:
    """Return whether an untracked path is an exact generated data output.

    Source adapters/receipts use namespace prefixes below, while formal data
    generation intentionally leaves only these three non-ignored files in the
    checkout.  Exact matching is deliberate: accepting a directory prefix
    would let an importable source shadow or arbitrary payload pass the
    fail-closed upstream-source gate.
    """

    if not isinstance(path, str):
        return False
    return path in ALLOWED_UNTRACKED_DATA_FILES


def load_yaml_mapping(path: str | Path) -> dict[str, Any]:
    """Load a YAML mapping without permitting an arbitrary config root.

    Keeping this tiny loader beside the guard makes every launcher path use
    the same parse/shape checks and avoids a second, subtly different YAML
    interpretation in the CLI.
    """

    config_path = Path(path).resolve()
    if not config_path.is_file():
        raise FileNotFoundError(config_path)
    try:
        import yaml
    except ModuleNotFoundError as exc:  # pragma: no cover - runtime dependency
        raise RuntimeError("PyYAML is required to resolve RAE config") from exc
    value = yaml.safe_load(config_path.read_text(encoding="utf-8"))
    if not isinstance(value, Mapping):
        raise ValueError(f"YAML config root must be a mapping: {config_path}")
    return dict(value)


def sha256_file(path: str | Path) -> str:
    path = Path(path)
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def git_commit(repo_root: str | Path) -> str:
    root = Path(repo_root)
    try:
        return subprocess.check_output(
            ["git", "-C", str(root), "rev-parse", "HEAD"],
            text=True,
            stderr=subprocess.STDOUT,
            env=_clean_git_environment(),
        ).strip()
    except (OSError, subprocess.CalledProcessError) as exc:
        raise RuntimeError(f"could not resolve official RAE commit below {root}") from exc


DIAGNOSTIC_PLANNER_SHA256 = "99ee9f7f7500c261561cf22b2539ccb38d13b3d8ae81ef1bf484c3a426678d35"
DIAGNOSTIC_SOURCE_VARIANT = "diagnostic_configurable_euler_v1"


def verify_upstream_source(
    repo_root: str | Path,
    *,
    expected_commit: str = OFFICIAL_COMMIT,
    expected_hashes: Mapping[str, str] = OFFICIAL_RESTRICTED_SHA256,
    diagnostic_inference: bool = False,
) -> dict[str, Any]:
    """Verify only the model/training/planner source surface used by B1."""

    root = Path(repo_root).resolve()
    actual_commit = git_commit(root)
    if actual_commit != expected_commit:
        raise RuntimeError(
            f"official RAE commit mismatch: got {actual_commit}, expected {expected_commit}"
        )
    if diagnostic_inference:
        expected_hashes = {**expected_hashes, "planning_eval.py": DIAGNOSTIC_PLANNER_SHA256}
    actual: dict[str, str] = {}
    mismatches: list[str] = []
    for relative, expected in expected_hashes.items():
        path = root / relative
        if not path.is_file():
            mismatches.append(f"missing:{relative}")
            continue
        digest = sha256_file(path)
        actual[relative] = digest
        if digest != expected:
            mismatches.append(f"sha:{relative}")
    if mismatches:
        raise RuntimeError("restricted official RAE SHA gate failed: " + ", ".join(mismatches))
    # Verify every tracked byte, not only the three executable entry points.
    # This catches edits to datasets.py/misc.py/RAE modules.  The sole
    # intentional executable exception is the exact reviewed accumulation
    # adapter in train.py; no other training/model source change is admitted.
    try:
        changed_output = subprocess.check_output(
            ["git", "-C", str(root), "diff", "--name-only", "-z", "HEAD", "--"],
            text=True,
            stderr=subprocess.STDOUT,
            env=_clean_git_environment(),
        )
        changed_paths = set(_git_path_records(changed_output))
    except (OSError, subprocess.CalledProcessError) as exc:
        raise RuntimeError(f"could not inspect official working-tree diff below {root}") from exc
    allowed_tracked_changes = set(ALLOWED_MODIFIED_CONFIG_SHA256)
    if diagnostic_inference:
        allowed_tracked_changes.add("planning_eval.py")
    if "train.py" in changed_paths:
        train_digest = actual.get("train.py")
        if train_digest != REVIEWED_ACCUMULATION_TRAIN_SHA256:
            raise RuntimeError("train.py differs from the reviewed accumulation adapter bytes")
        allowed_tracked_changes.add("train.py")
    unexpected = sorted(changed_paths - allowed_tracked_changes)
    if unexpected:
        raise RuntimeError("unexpected tracked official source/config changes: " + ", ".join(unexpected))
    config_actual: dict[str, str] = {}
    for relative, expected in ALLOWED_MODIFIED_CONFIG_SHA256.items():
        path = root / relative
        if not path.is_file():
            raise RuntimeError(f"missing required data/config file: {relative}")
        digest = sha256_file(path)
        config_actual[relative] = digest
        if digest != expected:
            raise RuntimeError(f"reviewed data/config SHA mismatch: {relative}")
    # Untracked adapter files are allowed only in their dedicated namespaces;
    # an untracked ``datasets.py``/``models.py`` shadow or arbitrary source
    # injection must fail closed.  Ignored data/model payloads remain outside
    # this source-tree check and are admitted separately by their asset gates.
    try:
        untracked_output = subprocess.check_output(
            ["git", "-C", str(root), "ls-files", "--others", "--exclude-standard", "-z"],
            text=True,
            stderr=subprocess.STDOUT,
            env=_clean_git_environment(),
        )
    except (OSError, subprocess.CalledProcessError) as exc:
        raise RuntimeError(f"could not inspect untracked official files below {root}") from exc
    # Runtime receipts are deliberately outside the executable authority
    # surface, but they live in the dedicated checkout so the launcher can
    # enforce canonical paths.  They must not be mistaken for source shadow
    # injection; the external authority verifier ignores this namespace.
    allowed_prefixes = ("rae_stream/", "scripts/", "tests/", "receipts/")
    allowed_files = {"config/rae_stream.yaml"}
    unexpected_untracked = []
    for path in _git_path_records(untracked_output):
        # ``splitlines`` removes only the record terminator.  Preserve all
        # other bytes so a filename with leading/trailing whitespace cannot be
        # normalized into one of the exact generated-data names below.
        if any(character.isspace() or ord(character) < 32 or ord(character) == 127 for character in path):
            unexpected_untracked.append(path)
            continue
        if (
            path not in allowed_files
            and not path.startswith(allowed_prefixes)
            and not is_allowed_untracked_path(path)
        ):
            unexpected_untracked.append(path)
    if unexpected_untracked:
        raise RuntimeError(
            "unexpected untracked source shadow/injection: " + ", ".join(sorted(unexpected_untracked))
        )
    return {
        "commit": actual_commit,
        "files": actual,
        "baseline_files": dict(OFFICIAL_BASELINE_RESTRICTED_SHA256),
        "training_source_variant": ACCUMULATION_SOURCE_VARIANT,
        **({"diagnostic_source_variant": DIAGNOSTIC_SOURCE_VARIANT} if diagnostic_inference else {}),
        "tracked_worktree_changes": sorted(changed_paths),
        "data_config_files": config_actual,
        "untracked_adapter_paths": sorted(
            _path for _path in _git_path_records(untracked_output)
        ),
    }


def verify_converter_source(
    repo_root: str | Path,
    *,
    expected_sha256: str = REVIEWED_CONVERTER_SHA256,
) -> str:
    """Verify the reviewed data-converter bytes in a RAE-stream checkout."""

    root = Path(repo_root).resolve()
    actual: dict[str, str] = {}
    mismatches: list[str] = []
    for relative, expected in REVIEWED_CONVERTER_CLOSURE_SHA256.items():
        path = root / relative
        if not path.is_file():
            mismatches.append(f"missing:{relative}")
            continue
        digest = sha256_file(path)
        actual[relative] = digest
        if digest != expected:
            mismatches.append(f"sha:{relative}")
    entry = actual.get("scripts/prepare_rae_stream.py")
    if entry != str(expected_sha256):
        mismatches.append("sha:scripts/prepare_rae_stream.py:entry-point")
    if mismatches:
        raise RuntimeError("RAE-stream converter closure SHA gate failed: " + ", ".join(mismatches))
    return entry


def converter_closure_digest_map(repo_root: str | Path) -> dict[str, str]:
    """Return the current SHA map for the converter's semantic source closure."""

    root = Path(repo_root).resolve()
    result: dict[str, str] = {}
    for relative in REVIEWED_CONVERTER_CLOSURE_SHA256:
        path = root / relative
        if not path.is_file():
            raise FileNotFoundError(path)
        result[relative] = sha256_file(path)
    return result


def converter_bundle_sha256(digests: Mapping[str, str]) -> str:
    """Hash a canonical relative-path→SHA map for manifest provenance."""

    payload = json.dumps(dict(sorted(digests.items())), sort_keys=True, separators=(",", ":")).encode("utf-8")
    return hashlib.sha256(payload).hexdigest()


def canonical_digest(value: Any) -> str:
    """Digest a JSON-serializable resolved config/manifest identity."""

    payload = json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":")).encode("utf-8")
    return hashlib.sha256(payload).hexdigest()


def assert_no_fixed_runtime_paths(value: Any) -> None:
    """Reject accidental machine-specific absolute/GPU settings in overlays."""

    def walk(item: Any, path: str = "") -> Iterable[tuple[str, str]]:
        if isinstance(item, Mapping):
            for key, child in item.items():
                yield from walk(child, f"{path}.{key}" if path else str(key))
        elif isinstance(item, (list, tuple)):
            for index, child in enumerate(item):
                yield from walk(child, f"{path}[{index}]")
        elif isinstance(item, str):
            yield path, item

    bad: list[str] = []
    for path, text in walk(value):
        lower = text.lower()
        if lower.startswith(("/home/", "/data/", "/mnt/", "cuda:")) or "cuda_visible_devices" in lower:
            bad.append(f"{path}={text!r}")
    if bad:
        raise ValueError("config contains fixed machine/GPU paths: " + "; ".join(bad))


