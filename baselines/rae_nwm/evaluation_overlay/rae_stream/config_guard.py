def training_profile_name(gradient_accumulation_steps: int) -> str:
    """Return the receipt label for an exact runtime accumulation factor."""

    if isinstance(gradient_accumulation_steps, bool) or not isinstance(
        gradient_accumulation_steps, numbers.Integral
    ):
        raise ValueError("gradient_accumulation_steps must be a positive integer")
    steps = int(gradient_accumulation_steps)
    if steps <= 0:
        raise ValueError("gradient_accumulation_steps must be a positive integer")
    return ACCUMULATION_PROFILE_NAME if steps > 1 else PAPER_PROFILE_NAME

