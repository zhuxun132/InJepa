def paper_batch_mapping(
    config: Mapping[str, Any],
    *,
    world_size: int = 1,
    gradient_accumulation_steps: int | None = None,
) -> dict[str, int]:
    """Validate the paper's total batch and return its DDP decomposition.

    Upstream ``train.py`` interprets ``batch_size`` per process.  Keeping this
    check outside the upstream file lets a scheduler choose a world size
    without silently changing the paper's total batch of 96.  A resolved
    runtime config may additionally split that per-rank batch into explicit
    gradient-accumulation microbatches.  For compatibility, an old-style
    config with no accumulation field and no explicit argument returns the
    historical three-key mapping.
    """

    if isinstance(world_size, bool) or not isinstance(world_size, int) or world_size <= 0:
        raise ValueError("world_size must be a positive integer")
    if not isinstance(config, Mapping):
        raise TypeError("config must be a mapping")
    world = world_size
    total = int(PAPER_TRAINING_PROFILE["global_batch_size"])
    include_runtime_fields = (
        gradient_accumulation_steps is not None
        or "gradient_accumulation_steps" in config
        or "effective_global_batch_size" in config
    )
    raw_steps = (
        gradient_accumulation_steps
        if gradient_accumulation_steps is not None
        else config.get("gradient_accumulation_steps", 1)
    )
    try:
        plan = make_accumulation_plan(
            global_batch_size=total,
            world_size=world,
            accumulation_steps=raw_steps,
        )
    except (TypeError, ValueError) as exc:
        raise ValueError(f"invalid paper batch/accumulation mapping (must divide evenly): {exc}") from exc
    if "gradient_accumulation_steps" in config:
        configured_steps = config["gradient_accumulation_steps"]
        try:
            configured_steps_int = require_positive_int(
                configured_steps, name="config gradient_accumulation_steps"
            )
        except ValueError as exc:
            raise ValueError("config gradient_accumulation_steps must be an integer") from exc
        if configured_steps_int != plan.accumulation_steps:
            raise ValueError(
                "config gradient_accumulation_steps does not match the requested runtime mapping"
            )
    if "effective_global_batch_size" in config:
        configured_effective = config["effective_global_batch_size"]
        try:
            configured_effective_int = require_positive_int(
                configured_effective, name="config effective_global_batch_size"
            )
        except ValueError as exc:
            raise ValueError("config effective_global_batch_size must be an integer") from exc
        if configured_effective_int != plan.effective_global_batch_size:
            raise ValueError("config effective_global_batch_size does not equal paper global batch 96")
    if "training_profile" in config and config["training_profile"] != training_profile_name(plan.accumulation_steps):
        raise ValueError("config training_profile does not match the accumulation mapping")
    if "paper_training_profile" in config and config["paper_training_profile"] != PAPER_PROFILE_NAME:
        raise ValueError("config paper_training_profile must be paper-reproduction-v1")
    expected_local = plan.microbatch_size
    raw_batch = config.get("batch_size", _MISSING)
    try:
        actual_local = require_positive_int(raw_batch, name="config batch_size")
    except ValueError as exc:
        raise ValueError("config batch_size must be an integer") from exc
    if actual_local != expected_local:
        raise ValueError(
            "paper global batch mapping mismatch: "
            f"world_size={world}, expected per-rank batch={expected_local}, got {raw_batch!r}"
        )
    result = {
        "global_batch_size": total,
        "world_size": world,
        "per_rank_batch_size": expected_local,
    }
    if include_runtime_fields:
        result.update(
            {
                "gradient_accumulation_steps": plan.accumulation_steps,
                "microbatch_global_size": plan.microbatch_global_size,
                "effective_global_batch_size": plan.effective_global_batch_size,
            }
        )
    return result


