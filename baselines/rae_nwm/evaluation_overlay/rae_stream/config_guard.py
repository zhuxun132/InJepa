def _clean_git_environment() -> dict[str, str]:
    """Remove caller-controlled Git repository/config overrides."""

    import os

    return {
        key: value
        for key, value in os.environ.items()
        if not (
            key in {"GIT_DIR", "GIT_WORK_TREE", "GIT_INDEX_FILE", "GIT_OBJECT_DIRECTORY"}
            or key.startswith("GIT_CONFIG_")
            or key in {"GIT_ALTERNATE_OBJECT_DIRECTORIES", "GIT_CEILING_DIRECTORIES"}
        )
    }


def _git_path_records(output: str) -> list[str]:
    """Parse Git path output without treating Unicode separators as newlines.

    Formal source checks request ``-z`` output, where NUL is the only record
    terminator and arbitrary embedded newlines remain part of a filename.  A
    newline fallback keeps this helper usable with small mocked/legacy Git
    commands in tests, but deliberately uses ``split("\\n")`` rather than
    ``splitlines()`` so U+2028/U+2029/U+0085 cannot truncate a path.
    """

    if not isinstance(output, str):
        raise TypeError("Git path output must be text")
    delimiter = "\0" if "\0" in output else "\n"
    records = output.split(delimiter)
    if delimiter == "\n":
        records = [record[:-1] if record.endswith("\r") else record for record in records]
    return [record for record in records if record]


